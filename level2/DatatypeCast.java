package level2;

public class DatatypeCast {
	public static void main(String[] args) {
		// implicit casting 
		byte b= 100;
		short s = 12345;
		int i =b;
		System.out.println(i);
		i=s;
		System.out.println(i);
		int i2 = 100123;
		i=i2;
		System.out.println(i);
		
		
		//Explicit type casting 
		
	}
}
